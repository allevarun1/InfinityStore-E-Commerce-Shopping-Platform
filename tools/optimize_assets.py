"""
Shrinks what the storefront sends to shoppers. Run after adding photos or icons:

    python tools/optimize_assets.py

1. Photos: every ecommerce-frontend/public/images/sarees/*.jpg gets 400px and 800px WebP copies (name-400.webp,
   name-800.webp). The app serves these through imageSet() in src/lib/format.js and falls back to the jpg.
2. Icons: the Bootstrap Icons font is 134 KB plus 90 KB of CSS for 2,000 glyphs; the store uses about 90. This writes a
   subset font and stylesheet containing only the icons named (bi-...) in src/, to src/icons/.

Needs: pip install pillow fonttools brotli
"""
import pathlib
import re

from fontTools import subset
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent / "ecommerce-frontend"
PHOTOS = ROOT / "public" / "images" / "sarees"
ICON_DIR = ROOT / "src" / "icons"
BI = ROOT / "node_modules" / "bootstrap-icons" / "font"


def photos():
    total_before = total_after = 0
    for jpg in sorted(PHOTOS.glob("*.jpg")):
        im = Image.open(jpg).convert("RGB")
        total_before += jpg.stat().st_size
        for w in (400, 800):
            if im.width < w:
                continue
            out = jpg.with_name(f"{jpg.stem}-{w}.webp")
            im.resize((w, round(im.height * w / im.width)), Image.LANCZOS).save(out, "WEBP", quality=76, method=6)
            if w == 800:
                total_after += out.stat().st_size
    print(f"photos: {total_before // 1024} KB of jpg -> {total_after // 1024} KB of 800px WebP (400px copies are smaller still)")


def icons():
    css = (BI / "bootstrap-icons.css").read_text(encoding="utf-8")
    codes = dict(re.findall(r'\.(bi-[a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css))
    used = set()
    for f in (ROOT / "src").rglob("*"):
        if f.suffix in (".jsx", ".js", ".css") and "icons" not in f.parts:
            used |= set(re.findall(r"\bbi-[a-z0-9-]+", f.read_text(encoding="utf-8", errors="ignore")))
    missing = sorted(u for u in used if u not in codes and u not in ("bi-",))
    keep = sorted(u for u in used if u in codes)
    ICON_DIR.mkdir(exist_ok=True)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = []
    font = subset.load_font(str(BI / "fonts" / "bootstrap-icons.woff2"), opts)
    s = subset.Subsetter(opts)
    s.populate(unicodes=[int(codes[k], 16) for k in keep])
    s.subset(font)
    subset.save_font(font, str(ICON_DIR / "bi-subset.woff2"), opts)
    rules = "\n".join(f'.{k}::before {{ content: "\\{codes[k]}"; }}' for k in keep)
    (ICON_DIR / "bi-subset.css").write_text(
        "/* Generated by tools/optimize_assets.py: only the icons the store uses. */\n"
        '@font-face { font-display: swap; font-family: "bootstrap-icons"; src: url("./bi-subset.woff2") format("woff2"); }\n'
        '.bi::before, [class^="bi-"]::before, [class*=" bi-"]::before {\n'
        '  display: inline-block; font-family: bootstrap-icons !important; font-style: normal; font-weight: normal !important;\n'
        "  font-variant: normal; text-transform: none; line-height: 1; vertical-align: -0.125em;\n"
        "  -webkit-font-smoothing: antialiased; -moz-osx-font-smoothing: grayscale;\n}\n" + rules + "\n",
        encoding="utf-8")
    print(f"icons: kept {len(keep)} glyphs, font {(ICON_DIR / 'bi-subset.woff2').stat().st_size // 1024} KB "
          f"(was {(BI / 'fonts' / 'bootstrap-icons.woff2').stat().st_size // 1024} KB); not in the font: {missing}")


if __name__ == "__main__":
    photos()
    icons()
